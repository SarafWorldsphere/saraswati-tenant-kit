-- Restoring missing Legacy Tables (Scheduling, Sections, Blocks & Logs).

-- 1. SECTIONS
CREATE TABLE sections (
    section_id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id          uuid NOT NULL REFERENCES platform.tenants (tenant_id),
    section_code       text NOT NULL,
    display_order      integer,
    record_status      text,
    created_at         timestamptz DEFAULT now(),
    updated_at         timestamptz DEFAULT now(),
    CONSTRAINT sections_tenant_id_key UNIQUE (tenant_id, section_id)
);
CREATE INDEX sections_tenant_code_idx ON sections (tenant_id, section_code);

-- 2. PERIOD MASTER
CREATE TABLE period_master (
    period_id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id          uuid NOT NULL REFERENCES platform.tenants (tenant_id),
    academic_year      text,
    schedule_type      text,
    period_no          integer,
    period_label       text,
    start_time         time,
    end_time           time,
    is_teaching        boolean,
    CONSTRAINT period_master_tenant_id_key UNIQUE (tenant_id, period_id)
);
CREATE INDEX period_master_tenant_year_idx ON period_master (tenant_id, academic_year);

-- 3. TIMETABLE
CREATE TABLE timetable (
    timetable_id       bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id          uuid NOT NULL REFERENCES platform.tenants (tenant_id),
    academic_year      text,
    class_id           bigint,
    section            text,
    day_of_week        integer,
    period_no          integer,
    subject_name       text,
    teacher_id         text,
    CONSTRAINT timetable_tenant_id_key UNIQUE (tenant_id, timetable_id)
);
CREATE INDEX timetable_tenant_class_day_idx ON timetable (tenant_id, class_id, day_of_week);

-- 4. CLASS SCHEDULE
CREATE TABLE class_schedule (
    schedule_id        bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id          uuid NOT NULL REFERENCES platform.tenants (tenant_id),
    class_id           bigint,
    section            text,
    subject_id         bigint,
    subject_name       text,
    teacher_name       text,
    schedule_date      date,
    day_of_week        smallint,
    CONSTRAINT class_schedule_tenant_id_key UNIQUE (tenant_id, schedule_id)
);
CREATE INDEX class_schedule_tenant_date_idx ON class_schedule (tenant_id, schedule_date);

-- 5. CHAPTER CONTENT BLOCKS
CREATE TABLE chapter_content_blocks (
    block_id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id          uuid NOT NULL REFERENCES platform.tenants (tenant_id),
    chapter_id         bigint,
    chapter_content_id bigint,
    block_type         text,
    block_heading      text,
    block_sequence     integer,
    block_text         text,
    media_url          text,
    CONSTRAINT chapter_content_blocks_tenant_id_key UNIQUE (tenant_id, block_id)
);
CREATE INDEX chapter_content_blocks_tenant_content_idx ON chapter_content_blocks (tenant_id, chapter_content_id);

-- 6. STUDENT SELF ASSESSMENT
CREATE TABLE student_self_assessment (
    self_assessment_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id          uuid NOT NULL REFERENCES platform.tenants (tenant_id),
    student_id         bigint,
    subject_id         bigint,
    class_name         text,
    understanding_level text,
    confidence_score   integer,
    practice_status    text,
    remarks            text,
    CONSTRAINT student_self_assessment_tenant_id_key UNIQUE (tenant_id, self_assessment_id)
