-- 8. ROLE RESPONSE
CREATE TABLE role_response (
    id                 bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id          uuid NOT NULL REFERENCES platform.tenants (tenant_id),
    role_id            bigint,
    role_name          text,
    role_description   text,
    created_datetime   timestamptz,
    created_user_id    text,
    created_ip_address text,
    modified_datetime  timestamptz,
    modified_user_id   text,
    CONSTRAINT role_response_tenant_id_key UNIQUE (tenant_id, id)
);

-- 9. AUDIT LOG
CREATE TABLE audit_log (
    log_id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id          uuid NOT NULL REFERENCES platform.tenants (tenant_id),
    table_name         text,
    record_id          bigint,
    action_type        text,
    old_value          jsonb,
    new_value          jsonb,
    changed_by         bigint,
    changed_datetime   timestamptz DEFAULT now(),
    CONSTRAINT audit_log_tenant_id_key UNIQUE (tenant_id, log_id)
);
CREATE INDEX audit_log_tenant_table_idx ON audit_log (tenant_id, table_name);

-- 10. PLATFORM ACTIVITY LOGS
CREATE TABLE platform_activity_logs (
    log_id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id          uuid NOT NULL REFERENCES platform.tenants (tenant_id),
    user_id            text,
    role_name          text,
    activity_type      text,
    login_method       text,
    page_path          text,
    created_at         timestamptz DEFAULT now(),
    CONSTRAINT platform_activity_logs_tenant_id_key UNIQUE (tenant_id, log_id)
);