-- AI Chatbot and Student Analysis Tables

CREATE TABLE ai_chat_messages (
    message_id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id          uuid NOT NULL REFERENCES platform.tenants (tenant_id),
    student_id         bigint,
    teacher_id         bigint,
    role               text,
    message_content    text,
    created_at         timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT ai_chat_messages_tenant_id_key UNIQUE (tenant_id, message_id)
);

CREATE INDEX ai_chat_messages_tenant_student_idx 
    ON ai_chat_messages (tenant_id, student_id);
    
CREATE INDEX ai_chat_messages_tenant_teacher_idx 
    ON ai_chat_messages (tenant_id, teacher_id);

CREATE TABLE ai_student_analysis (
    ai_analysis_id       bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id            uuid NOT NULL REFERENCES platform.tenants (tenant_id),
    student_id           bigint NOT NULL,
    class_name           text,
    subject_id           bigint,
    analysis_type        text,
    analysis_summary     text,
    strengths            text,
    weak_areas           text,
    recommendations      text,
    focus_subjects       text,
    performance_level    text,
    generated_by_model   text,
    raw_ai_response      jsonb,
    created_datetime     timestamptz NOT NULL DEFAULT now(),
    created_user_id      text,
    created_ip_address   text,
    modified_datetime    timestamptz,
    modified_user_id     text,
    modified_ip_address  text,
    record_status        text,
    version_no           integer,
    CONSTRAINT ai_student_analysis_tenant_id_key UNIQUE (tenant_id, ai_analysis_id),
    CONSTRAINT ai_student_analysis_student_fk
        FOREIGN KEY (tenant_id, student_id) REFERENCES student_master (tenant_id, student_id)
);

CREATE INDEX ai_student_analysis_tenant_student_idx 
    ON ai_student_analysis (tenant_id, student_id);